#!/usr/bin/env python3
"""Generate SortedKeyFixtures.cs: CPython's text for ", ".join(sorted(set(data) - allowed)) with non-string keys.

work_ledger._item_data reports unknown item fields with ``", ".join(sorted(set(data) - allowed))``. A patch given
as a list of pairs can add None, bool, int and float keys, and then Python raises a TypeError whose text depends
on the set's iteration order and on list.sort's comparisons. Each case is a dict's key order; the expected text
is what this interpreter raises. Keys are None, bools, ints and floats, whose hashes do not depend on
PYTHONHASHSEED; unknown string keys are left out because their slots (and so Python's text) change with the
per-process string hash key. Cases whose text still differs under PYTHONHASHSEED 0..7 (an allowed string key
colliding with a number in the first set's table) are dropped.

Usage: python3 generate_sorted_key_fixtures.py   (writes SortedKeyFixtures.cs next to this file)
"""

import json
import os
import platform
import random
import subprocess
import sys
from pathlib import Path

ALLOWED = ["title", "owner", "direction", "due", "source_refs", "confidence", "outcome_id", "next_step", "blocker",
           "deferred_until", "notes", "confirmation_source"]
SEEDS = range(8)
ORACLE = """
import json, sys
allowed = set(json.loads(sys.argv[1]))
out = []
for keys in json.loads(sys.stdin.read()):
    try:
        ", ".join(sorted(set(dict.fromkeys(keys)) - allowed))
        out.append(None)
    except TypeError as exc:
        out.append(str(exc))
print(json.dumps(out))
"""


def random_key(rng):
    roll = rng.random()
    if roll < 0.12:
        return None
    if roll < 0.22:
        return rng.choice([True, False])
    if roll < 0.55:
        return rng.choice([rng.randint(-20, 40), rng.randint(-10 ** 30, 10 ** 30), 2 ** 61 - 1, 2 ** 61, -(2 ** 61),
                           2 ** 64 + rng.randint(0, 9), -1, -2])
    return rng.choice([rng.randint(-50, 50) / 4, rng.randint(1, 10 ** 6) / 1024, 5e-324, -0.0, 0.5, 1e300,
                       float(rng.randint(0, 64)), 1e16 + rng.randint(0, 9) * 2.0, -2.5])


def cases():
    rng = random.Random(20261107)
    fixed = [
        [2.5, 1, None], [3, 2.5, None], [None, 2.5, 1], [None, 0.5, -3, 10 ** 20], [1.5, 1, None], [True, None],
        [1, None], [None], [1, True], [2.5], [None, 7, 8], [0, None], [None, 0],
        [-1, -2, None], [2 ** 61 - 1, 2 ** 61, None], [5e-324, -0.0, None, 1e300],
    ]
    for extra in fixed:
        yield ["title", "owner", "due", "direction", "confirmation_source"] + extra
    for _ in range(600):
        keys = ["title", "owner", "due", "direction"] + rng.sample(ALLOWED[4:], rng.randint(1, 4))
        count = rng.choice([1, 2, 2, 3, 3, 4, 5, 6, 8, 12, 20, 40, 70, 130])
        extra = []
        for _ in range(count):
            key = random_key(rng)
            if not any(key == other for other in extra):
                extra.append(key)
        keys = list(dict.fromkeys(keys + extra))
        if any(not isinstance(key, str) for key in keys):
            yield keys


def oracle(all_cases, seed):
    env = {"PATH": os.environ.get("PATH", "/usr/bin:/bin"), "PYTHONHASHSEED": str(seed)}
    done = subprocess.run([sys.executable, "-P", "-s", "-c", ORACLE, json.dumps(ALLOWED)], input=json.dumps(all_cases),
                          capture_output=True, text=True, env=env, check=True)
    return json.loads(done.stdout)


def main():
    all_cases = list(cases())
    results = [oracle(all_cases, seed) for seed in SEEDS]
    kept = []
    for index, keys in enumerate(all_cases):
        texts = {result[index] for result in results}
        if len(texts) == 1 and None not in texts:
            kept.append((json.dumps(keys), texts.pop()))
    lines = [
        "// <auto-generated>",
        "// Generated by Work/generate_sorted_key_fixtures.py with CPython %s; do not edit by hand." % platform.python_version(),
        "// </auto-generated>",
        "#nullable enable",
        "using Xunit;",
        "",
        "namespace Margo.Cloud.State.Tests.Work;",
        "",
        "internal static class SortedKeyFixtures",
        "{",
        "    /// <summary>A dict's keys in insertion order (JSON) and CPython's join/sort TypeError text.</summary>",
        "    public static TheoryData<string, string> Cases => new()",
        "    {",
    ]
    for keys, text in kept:
        lines.append("        { %s, %s }," % (json.dumps(keys), json.dumps(text)))
    lines += ["    };", "}", ""]
    target = Path(__file__).with_name("SortedKeyFixtures.cs")
    target.write_text("\n".join(lines), encoding="utf-8")
    print("%d of %d cases are reproducible across hash seeds; wrote %s" % (len(kept), len(all_cases), target.name))


if __name__ == "__main__":
    main()
