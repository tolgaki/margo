#!/usr/bin/env python3
"""Regenerate PyUnicodeData.cs: the Unicode tables of the CPython the state helpers target.

    python3 cloud/src/Margo.Cloud.State.Core/generate_unicode_data.py

.NET carries its own Unicode tables (Unicode 16.0 in .NET 10) and its regular expressions see
UTF-16 code units, so ``str.isprintable()`` (``repr``), ``str.isdecimal()`` (``int()``, ``\\d``),
``str.casefold()``, ``str.isalnum()`` (``re``'s ``\\w``), ``str.isspace()`` (``\\s``),
``str.isdigit()`` and ``re.IGNORECASE`` would drift from CPython 3.13 (Unicode 15.1). The C# helpers
(``PyRepr``, ``PyText``) read these tables instead. Run with the CPython version the ports target and
review the diff before committing.
"""

import re
import sys
import unicodedata
from pathlib import Path

HERE = Path(__file__).resolve().parent
TARGET = HERE / "PyUnicodeData.cs"


def ranges(predicate):
    result, start = [], None
    for code in range(0x110000):
        if predicate(code):
            if start is None:
                start = code
        elif start is not None:
            result.append((start, code - 1))
            start = None
    if start is not None:
        result.append((start, 0x10FFFF))
    return result


def decimal_runs():
    """(first, last, value of first) runs of consecutive decimal digits with consecutive values."""
    runs = []
    for code in range(0x110000):
        char = chr(code)
        if not char.isdecimal():
            continue
        value = unicodedata.decimal(char)
        if runs and runs[-1][1] == code - 1 and runs[-1][2] + (code - runs[-1][0]) == value:
            runs[-1] = (runs[-1][0], code, runs[-1][2])
        else:
            runs.append((code, code, value))
    return runs


def cs_string(text):
    out = ['"']
    for char in text:
        code = ord(char)
        if 0x20 <= code < 0x7F and char not in '"\\':
            out.append(char)
        elif code > 0xFFFF:
            code -= 0x10000
            out.append("\\u%04x\\u%04x" % (0xD800 + (code >> 10), 0xDC00 + (code & 0x3FF)))
        else:
            out.append("\\u%04x" % code)
    out.append('"')
    return "".join(out)


def rows(items, per_line):
    lines = []
    for index in range(0, len(items), per_line):
        lines.append("        " + ", ".join(items[index:index + per_line]) + ",")
    return "\n".join(lines)


def main():
    printable = ranges(lambda code: not chr(code).isprintable())
    decimals = decimal_runs()
    folds = [(code, chr(code).casefold()) for code in range(0x110000)
             if not 0xD800 <= code <= 0xDFFF and chr(code).casefold() != chr(code)]
    alnum = ranges(lambda code: chr(code).isalnum())
    spaces = ranges(lambda code: chr(code).isspace())
    digits = ranges(lambda code: chr(code).isdigit())
    ignore_case = {}
    for letter in "abcdefghijklmnopqrstuvwxyz":
        pattern = re.compile("(?i)" + letter)
        extra = [code for code in range(0x80, 0x110000) if pattern.fullmatch(chr(code))]
        if extra:
            ignore_case[letter] = extra
    ignore_case_rows = ["['%s'] = [%s]," % (letter, ", ".join("0x%X" % code for code in codes))
                        for letter, codes in sorted(ignore_case.items())]
    text = f"""// <auto-generated>
// Generated by generate_unicode_data.py from CPython {sys.version.split()[0]} (Unicode {unicodedata.unidata_version}).
// Do not edit by hand; rerun the generator with the CPython version the ports target.
// </auto-generated>

namespace Margo.Cloud.State.Core;

/// <summary>Unicode {unicodedata.unidata_version} tables as CPython {sys.version_info.major}.{sys.version_info.minor} uses them.</summary>
internal static class PyUnicodeData
{{
    /// <summary>The Unicode version of these tables.</summary>
    public const string UnicodeVersion = "{unicodedata.unidata_version}";

    /// <summary>Inclusive ranges of code points for which <c>str.isprintable()</c> is false.</summary>
    public static readonly int[] NonPrintableRanges =
    [
{rows(["0x%X, 0x%X" % pair for pair in printable], 6)}
    ];

    /// <summary>Runs (first, last, decimal value of first) of code points for which <c>str.isdecimal()</c> is true.</summary>
    public static readonly int[] DecimalRuns =
    [
{rows(["0x%X, 0x%X, %d" % run for run in decimals], 5)}
    ];

    /// <summary>Code points whose <c>str.casefold()</c> differs from themselves, in ascending order.</summary>
    public static readonly int[] CaseFoldKeys =
    [
{rows(["0x%X" % code for code, _ in folds], 12)}
    ];

    /// <summary>The <c>str.casefold()</c> of each <see cref="CaseFoldKeys"/> entry.</summary>
    public static readonly string[] CaseFoldValues =
    [
{rows([cs_string(fold) for _, fold in folds], 12)}
    ];

    /// <summary>
    /// Inclusive ranges of code points for which <c>str.isalnum()</c> is true; <c>re</c>'s <c>\\w</c> in a <c>str</c>
    /// pattern is these and <c>_</c>.
    /// </summary>
    public static readonly int[] AlnumRanges =
    [
{rows(["0x%X, 0x%X" % pair for pair in alnum], 6)}
    ];

    /// <summary>Inclusive ranges of code points for which <c>str.isspace()</c> is true (<c>re</c>'s <c>\\s</c>).</summary>
    public static readonly int[] SpaceRanges =
    [
{rows(["0x%X, 0x%X" % pair for pair in spaces], 6)}
    ];

    /// <summary>Inclusive ranges of code points for which <c>str.isdigit()</c> is true.</summary>
    public static readonly int[] DigitRanges =
    [
{rows(["0x%X, 0x%X" % pair for pair in digits], 6)}
    ];

    /// <summary>Non-ASCII code points that <c>re.IGNORECASE</c> matches against an ASCII letter (besides its two cases).</summary>
    public static readonly Dictionary<char, int[]> IgnoreCaseExtras = new()
    {{
{chr(10).join("        " + row for row in ignore_case_rows)}
    }};
}}
"""
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    print("wrote %s: %d non-printable ranges, %d decimal runs, %d case folds, %d alnum ranges, %d space ranges, "
          "%d digit ranges, %d ignore-case letters"
          % (TARGET, len(printable), len(decimals), len(folds), len(alnum), len(spaces), len(digits), len(ignore_case)))


if __name__ == "__main__":
    main()
