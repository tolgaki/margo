#!/usr/bin/env python3
"""Regenerate MemoryUnicodeData.cs: the Unicode classes the memory regular expressions depend on.

    python3 cloud/src/Margo.Cloud.State.Memory/generate_memory_unicode_data.py

memory_store.py and memory_governance.py match identifiers, e-mail addresses and credential markers
with Python's ``re`` (``\\w``, ``\\b``, ``\\s``, ``(?i)``) and validate revisions with ``str.isdigit()``.
.NET's regular expressions use different Unicode classes (``\\w`` includes combining marks and
connector punctuation, excludes letter-like numerals) and a newer Unicode version, so the C# port
matches with these tables, generated from the CPython the ports target (3.13, Unicode 15.1). Run
it with that CPython and review the diff before committing. The tables belong in State.Core's
PyUnicodeData once another port needs them.
"""

import re
import sys
import unicodedata
from pathlib import Path

HERE = Path(__file__).resolve().parent
TARGET = HERE / "MemoryUnicodeData.cs"


def ranges(predicate):
    result, start = [], None
    for code in range(0x110000):
        if predicate(code):
            if start is None:
                start = code
        elif start is not None:
            result.append((start, code - 1))
            start = None
    if start is not None:
        result.append((start, 0x10FFFF))
    return result


def rows(items, per_line):
    lines = []
    for index in range(0, len(items), per_line):
        lines.append("        " + ", ".join(items[index:index + per_line]) + ",")
    return "\n".join(lines)


def main():
    word = re.compile(r"\w")
    space = re.compile(r"\s")
    words = ranges(lambda code: word.fullmatch(chr(code)) is not None)
    spaces = ranges(lambda code: space.fullmatch(chr(code)) is not None)
    digits = ranges(lambda code: chr(code).isdigit())
    folds = {}
    for letter in "abcdefghijklmnopqrstuvwxyz":
        pattern = re.compile("(?i)" + letter)
        extra = [code for code in range(0x80, 0x110000) if pattern.fullmatch(chr(code))]
        if extra:
            folds[letter] = extra
    fold_rows = ["['%s'] = [%s]," % (letter, ", ".join("0x%X" % code for code in codes))
                 for letter, codes in sorted(folds.items())]
    text = f"""// <auto-generated>
// Generated by generate_memory_unicode_data.py from CPython {sys.version.split()[0]} (Unicode {unicodedata.unidata_version}).
// Do not edit by hand; rerun the generator with the CPython version the ports target.
// </auto-generated>

namespace Margo.Cloud.State.Memory;

/// <summary>Python <c>re</c> character classes and <c>str.isdigit()</c> as CPython {sys.version_info.major}.{sys.version_info.minor} defines them (Unicode {unicodedata.unidata_version}).</summary>
internal static class MemoryUnicodeData
{{
    /// <summary>The Unicode version of these tables.</summary>
    public const string UnicodeVersion = "{unicodedata.unidata_version}";

    /// <summary>Inclusive ranges of code points that <c>re</c>'s <c>\\w</c> matches in a <c>str</c> pattern (<c>isalnum()</c> or <c>_</c>).</summary>
    public static readonly int[] WordRanges =
    [
{rows(["0x%X, 0x%X" % pair for pair in words], 6)}
    ];

    /// <summary>Inclusive ranges of code points that <c>re</c>'s <c>\\s</c> matches (the same as <c>str.isspace()</c>).</summary>
    public static readonly int[] SpaceRanges =
    [
{rows(["0x%X, 0x%X" % pair for pair in spaces], 6)}
    ];

    /// <summary>Inclusive ranges of code points for which <c>str.isdigit()</c> is true.</summary>
    public static readonly int[] DigitRanges =
    [
{rows(["0x%X, 0x%X" % pair for pair in digits], 6)}
    ];

    /// <summary>Non-ASCII code points that <c>re.IGNORECASE</c> matches against an ASCII letter (besides its two cases).</summary>
    public static readonly Dictionary<char, int[]> IgnoreCaseExtras = new()
    {{
{chr(10).join("        " + row for row in fold_rows)}
    }};
}}
"""
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    print("wrote %s: %d word ranges, %d space ranges, %d digit ranges, %d ignore-case letters"
          % (TARGET, len(words), len(spaces), len(digits), len(folds)))


if __name__ == "__main__":
    main()
