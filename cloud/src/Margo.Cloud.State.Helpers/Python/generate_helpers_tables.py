#!/usr/bin/env python3
"""Regenerate PyHelpersTables.cs: the CPython tables the stateless helpers rely on.

    python3 cloud/src/Margo.Cloud.State.Helpers/Python/generate_helpers_tables.py

``html.unescape`` (teams_feedback.py): the HTML5 named character references
(``html.entities.html5``) and the ``_invalid_charrefs``/``_invalid_codepoints`` tables of
``Lib/html/__init__.py``. The Unicode classes (``re``'s ``\\w``, ``str.isalnum()``) are shared by
every port and live in State.Core's ``PyUnicodeData`` (``generate_unicode_data.py``).

Run with the CPython version the ports target (3.13) and review the diff before committing.
"""

import html
import html.entities
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
TARGET = HERE / "PyHelpersTables.cs"


def cs_string(text):
    out = ['"']
    for char in text:
        code = ord(char)
        if 0x20 <= code < 0x7F and char not in '"\\':
            out.append(char)
        elif code > 0xFFFF:
            code -= 0x10000
            out.append("\\u%04x\\u%04x" % (0xD800 + (code >> 10), 0xDC00 + (code & 0x3FF)))
        else:
            out.append("\\u%04x" % code)
    out.append('"')
    return "".join(out)


def int_rows(values, per_line=12):
    lines = []
    for index in range(0, len(values), per_line):
        lines.append("        " + ", ".join("0x%X" % value for value in values[index:index + per_line]) + ",")
    return lines


def main():
    if sys.version_info[:2] != (3, 13):
        print("warning: the ports target CPython 3.13; this is %d.%d" % sys.version_info[:2], file=sys.stderr)
    entities = sorted(html.entities.html5.items())
    charrefs = sorted(html._invalid_charrefs.items())
    codepoints = sorted(html._invalid_codepoints)

    lines = [
        "// <auto-generated>",
        "// Generated by generate_helpers_tables.py from CPython %d.%d.%d."
        % (sys.version_info[0], sys.version_info[1], sys.version_info[2]),
        "// Do not edit by hand; rerun the generator with the CPython version the ports target.",
        "// </auto-generated>",
        "",
        "namespace Margo.Cloud.State.Helpers.Python;",
        "",
        "/// <summary>CPython 3.13 tables for <c>html.unescape</c>.</summary>",
        "internal static class PyHelpersTables",
        "{",
        "    /// <summary><c>html.entities.html5</c>: name (with or without its <c>;</c>) to replacement text.</summary>",
        "    public static readonly KeyValuePair<string, string>[] Html5 =",
        "    [",
    ]
    for name, value in entities:
        lines.append("        new(%s, %s)," % (cs_string(name), cs_string(value)))
    lines += [
        "    ];",
        "",
        "    /// <summary><c>html._invalid_charrefs</c>: numeric references replaced per the HTML5 standard.</summary>",
        "    public static readonly KeyValuePair<int, string>[] InvalidCharrefs =",
        "    [",
    ]
    for number, value in charrefs:
        lines.append("        new(0x%X, %s)," % (number, cs_string(value)))
    lines += [
        "    ];",
        "",
        "    /// <summary><c>html._invalid_codepoints</c>: numeric references that expand to nothing.</summary>",
        "    public static readonly int[] InvalidCodepoints =",
        "    [",
    ]
    lines += int_rows(codepoints)
    lines += ["    ];", "}", ""]
    TARGET.write_text("\n".join(lines), encoding="utf-8")
    print("wrote %s: %d entities, %d invalid charrefs, %d invalid codepoints"
          % (TARGET, len(entities), len(charrefs), len(codepoints)))


if __name__ == "__main__":
    main()
